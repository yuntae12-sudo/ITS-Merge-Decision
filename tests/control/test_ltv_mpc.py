def test_straight_constant_speed_tracking():
    config = make_config()
    controller = LtvMpcController(config)
    target_speed = 15.0

    # Fixed lane at y=0 (NOT re-anchored to the current state's own y
    # each call) -- this is what actually exercises "converge to and
    # hold the reference," since a reference that re-anchors to
    # wherever the vehicle currently is would never ask it to correct
    # an initial lateral offset.
    def reference_fn(state):
        return straight_reference(state.x, 0.0, 0.0, target_speed, HORIZON, MPC_DT_S)

    state = ControllerState(x=0.0, y=2.0, yaw=0.05, speed=10.0)  # slight offset + speed gap
    trajectory = run_to_convergence(controller, state, reference_fn, steps=40)

    final = trajectory[-1]
    assert abs(final.speed - target_speed) < 1.0
    assert abs(final.yaw) < 0.1
    assert abs(final.y) < 1.0


def test_speed_increase_tracking():
    config = make_config()
    controller = LtvMpcController(config)

    def reference_fn(state):
        return speed_profile_reference(state.x, state.y, 0.0, state.speed, accel=2.0, horizon=HORIZON, dt=MPC_DT_S)

    state = ControllerState(x=0.0, y=0.0, yaw=0.0, speed=5.0)
    trajectory = run_to_convergence(controller, state, reference_fn, steps=30)

    speeds = [s.speed for s in trajectory]
    assert speeds[-1] > speeds[0] + 5.0  # meaningfully accelerated


