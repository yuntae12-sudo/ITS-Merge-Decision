def test_control_saturation_clips_to_bounds():
    """A reference requiring far more accel/steering than the box
    bounds allow must produce a command clipped to bounds, not one
    silently exceeding them."""

    config = make_config()
    controller = LtvMpcController(config)

    # Reference far ahead and to the side, demanding an enormous
    # speed/heading change within one horizon -- forces saturation.
    reference = [
        ReferencePoint(x=1000.0 * (i + 1), y=500.0 * (i + 1), yaw=1.5, speed=100.0)
        for i in range(HORIZON)
    ]
    state = ControllerState(x=0.0, y=0.0, yaw=0.0, speed=0.0)
    result = controller.solve(state, reference)

    assert result.status == ControllerStatus.OK
    assert abs(result.command.acceleration_mps2) <= MAX_ACCEL_MPS2 + 1e-9
    assert abs(result.command.steering_curvature) <= MAX_STEERING_CURVATURE + 1e-9
    assert np.all(np.abs(result.horizon_commands[:, 0]) <= MAX_ACCEL_MPS2 + 1e-9)
    assert np.all(np.abs(result.horizon_commands[:, 1]) <= MAX_STEERING_CURVATURE + 1e-9)
    # Given the extreme reference, saturation should actually bind.
    assert np.any(np.isclose(np.abs(result.horizon_commands[:, 0]), MAX_ACCEL_MPS2, atol=1e-3))


