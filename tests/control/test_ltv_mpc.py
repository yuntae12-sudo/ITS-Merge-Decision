"""Stage 3-D: LTV-MPC solve-loop tests.

Covers the required synthetic tracking scenarios (straight, arcs,
offsets, speed changes), control saturation, non-finite rejection,
warm-start behavior, and reset behavior -- see the task brief's
"Required tests" list. All scenarios track a HAND-BUILT reference
(this stage does not wire into Stage 3-C's planner output -- that is
Stage 3-E).
"""

import numpy as np
import pytest

from src.control import vehicle_model
from src.control.ltv_mpc import LtvMpcController, MpcConfig, load_mpc_config
from src.control.mpc_cost import CostWeights
from src.control.mpc_types import (
    MAX_ACCEL_MPS2,
    MAX_STEERING_CURVATURE,
    MPC_DT_S,
    ControllerState,
    ControllerStatus,
    ReferencePoint,
)

HORIZON = 20


def make_config(horizon=HORIZON, max_iterations=200):
    weights = CostWeights(
        w_pos=10.0, w_yaw=5.0, w_speed=2.0,
        w_accel_effort=0.05, w_steering_effort=0.05,
        w_accel_rate=0.1, w_steering_rate=0.1,
        w_terminal_pos=20.0, w_terminal_yaw=10.0, w_terminal_speed=5.0,
    )
    return MpcConfig(horizon=horizon, dt_s=MPC_DT_S, weights=weights, max_iterations=max_iterations)


def straight_reference(start_x, start_y, yaw, speed, horizon, dt):
    """Constant-speed, constant-heading straight-line reference."""

    ref = []
    x, y = start_x, start_y
    for _ in range(horizon):
        x += speed * np.cos(yaw) * dt
        y += speed * np.sin(yaw) * dt
        ref.append(ReferencePoint(x=x, y=y, yaw=yaw, speed=speed))
    return ref


def speed_profile_reference(start_x, start_y, yaw, start_speed, accel, horizon, dt):
    """Constant-heading, constant-acceleration reference (used for
    both the speed-increase and speed-decrease tests)."""

    ref = []
    x, y = start_x, start_y
    speed = start_speed
    for _ in range(horizon):
        x += speed * np.cos(yaw) * dt + 0.5 * accel * np.cos(yaw) * dt**2
        y += speed * np.sin(yaw) * dt + 0.5 * accel * np.sin(yaw) * dt**2
        speed += accel * dt
        ref.append(ReferencePoint(x=x, y=y, yaw=yaw, speed=speed))
    return ref


def arc_reference(start_x, start_y, yaw, speed, curvature, horizon, dt):
    """Constant-speed, constant-curvature arc reference (generated by
    forward-simulating vehicle_model.step with a constant steering
    command at zero acceleration -- an exact, self-consistent arc
    under this same forward model)."""

    state = np.array([start_x, start_y, yaw, speed])
    control = np.array([0.0, curvature])
    ref = []
    for _ in range(horizon):
        state = vehicle_model.step(state, control, dt=dt, clip_control=False)
        ref.append(ReferencePoint(x=state[0], y=state[1], yaw=state[2], speed=state[3]))
    return ref


def run_to_convergence(controller, state, reference_fn, steps=40):
    """Repeatedly solves + advances the true nonlinear state one MPC
    step at a time (closed loop), regenerating the reference horizon
    fresh each step relative to the CURRENT state's own forward arc.
    Returns the list of states visited."""

    trajectory = [state]
    for _ in range(steps):
        reference = reference_fn(state)
        result = controller.solve(state, reference)
        assert result.status == ControllerStatus.OK, result.error
        command = result.command.as_array()
        next_state_arr = vehicle_model.step(state.as_array(), command, dt=MPC_DT_S, clip_control=True)
        state = ControllerState.from_array(next_state_arr)
        trajectory.append(state)
    return trajectory


