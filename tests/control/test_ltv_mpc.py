def test_warm_start_no_worse_than_cold_start():
    """A second consecutive solve using the warm-started previous
    solution should not produce a worse (higher) FIRST-iterate cost
    than an independent cold-start solve on the same problem --
    measured here as: the warm-started solve's final cost is <= the
    cold-start solve's final cost (both given the same iteration
    budget), since warm-starting from a near-optimal previous solution
    should already be close to optimal for a slowly-changing
    continuing trajectory.
    """

    config = make_config(max_iterations=50)
    controller_warm = LtvMpcController(config)
    controller_cold = LtvMpcController(config)

    target_speed = 12.0
    state = ControllerState(x=0.0, y=1.0, yaw=0.02, speed=10.0)
    reference = straight_reference(state.x, state.y, 0.0, target_speed, HORIZON, MPC_DT_S)

    # First solve seeds controller_warm's warm-start.
    first_result = controller_warm.solve(state, reference)
    assert first_result.status == ControllerStatus.OK

    # Advance state one step under the first solved command (both
    # controllers see the same next state/reference).
    next_state_arr = vehicle_model.step(
        state.as_array(), first_result.command.as_array(), dt=MPC_DT_S, clip_control=True
    )
    next_state = ControllerState.from_array(next_state_arr)
    next_reference = straight_reference(next_state.x, next_state.y, 0.0, target_speed, HORIZON, MPC_DT_S)

    warm_result = controller_warm.solve(next_state, next_reference)
    cold_result = controller_cold.solve(next_state, next_reference)

    assert warm_result.status == ControllerStatus.OK
    assert cold_result.status == ControllerStatus.OK
    # Warm start should reach at least as good a cost (small tolerance
    # for solver noise/non-convexity of the underlying nonlinear
    # rollout).
    assert warm_result.cost <= cold_result.cost + 1e-3


def test_reset_clears_warm_start_state():
    config = make_config()
    controller = LtvMpcController(config)
    state = ControllerState(x=0.0, y=1.0, yaw=0.02, speed=10.0)
    reference = straight_reference(state.x, state.y, 0.0, 12.0, HORIZON, MPC_DT_S)

    result1 = controller.solve(state, reference)
    assert result1.status == ControllerStatus.OK
    assert controller._warm_start is not None

    controller.reset()
    assert controller._warm_start is None
    assert controller._previous_command is None

    # After reset, a fresh solve should use the default (zero) initial
    # guess, exactly like a brand-new controller instance would.
    fresh_controller = LtvMpcController(config)
    result_after_reset = controller.solve(state, reference)
    result_fresh = fresh_controller.solve(state, reference)
    assert result_after_reset.status == ControllerStatus.OK
    assert result_fresh.status == ControllerStatus.OK
    np.testing.assert_allclose(
        result_after_reset.horizon_commands, result_fresh.horizon_commands, atol=1e-6
    )


